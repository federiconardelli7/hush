// Generates src/features/eerc/prover/snarkjsSource.gen.ts from the installed
// snarkjs browser build. Runs on postinstall so it always matches the locked
// snarkjs version. The output is gitignored.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "node_modules/snarkjs/build/snarkjs.min.js");
const outPath = resolve(root, "src/features/eerc/prover/snarkjsSource.gen.ts");

const raw = readFileSync(sourcePath, "utf8");
// Inline-script safety: a literal "</script" inside the source would close the
// prover page's <script> tag early. "<\/" is identical to "/" in JS source.
const safe = raw.replace(/<\/script/gi, "<\\/script");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  "// GENERATED by scripts/gen-snarkjs-source.mjs (postinstall) — do not edit.\n" +
    "// The snarkjs browser build, inlined into the ProverHost WebView page.\n" +
    `export const SNARKJS_SRC = ${JSON.stringify(safe)};\n`,
);
console.log(`gen-snarkjs-source: wrote ${outPath} (${safe.length} chars)`);
